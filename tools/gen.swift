import Foundation

let arguments = CommandLine.arguments.dropFirst()
let copyOnly = arguments.contains("--copy-only")
let root = URL(fileURLWithPath: arguments.first(where: { $0 != "--copy-only" }) ?? ".")
let resources = root.appendingPathComponent("resources")

func parseCSV(_ text: String) -> [[String]] {
    var rows: [[String]] = [], row: [String] = [], cell = "", quoted = false
    var chars = Array(text)
    var i = 0
    while i < chars.count {
        let c = chars[i]
        if quoted {
            if c == "\"" && i + 1 < chars.count && chars[i + 1] == "\"" { cell.append("\""); i += 1 }
            else if c == "\"" { quoted = false }
            else { cell.append(c) }
        } else if c == "\"" { quoted = true }
        else if c == "," { row.append(cell); cell = "" }
        else if c == "\n" { row.append(cell); rows.append(row); row = []; cell = "" }
        else if c != "\r" { cell.append(c) }
        i += 1
    }
    if !cell.isEmpty || !row.isEmpty { row.append(cell); rows.append(row) }
    chars.removeAll()
    return rows
}

func swiftLiteral(_ s: String) -> String {
    var out = "\""
    for ch in s.unicodeScalars {
        switch ch {
        case "\\": out += "\\\\"
        case "\"": out += "\\\""
        case "\n": out += "\\n"
        default: out.unicodeScalars.append(ch)
        }
    }
    return out + "\""
}

// Effective German catalog: first source wins, app entries override earlier sources.
func entries(_ rows: [[String]], into result: inout [String: String], override: Bool = false) {
    guard let header = rows.first, let ki = header.firstIndex(of: "key"), let ti = header.firstIndex(of: "text") else {
        fatalError("Copy CSV requires key,text columns")
    }
    for row in rows.dropFirst() where row.count > max(ki, ti) && !row[ki].isEmpty {
        if override || result[row[ki]] == nil { result[row[ki]] = row[ti] }
    }
}
func readCSV(_ name: String) throws -> [[String]] {
    parseCSV(try String(contentsOf: resources.appendingPathComponent(name), encoding: .utf8))
}
var german: [String: String] = [:]
entries(try readCSV("copy.csv"), into: &german)
let supplementURL = resources.appendingPathComponent("copy-supplement.csv")
if let text = try? String(contentsOf: supplementURL, encoding: .utf8) {
    entries(parseCSV(text), into: &german)
}
entries(try readCSV("copy-app.csv"), into: &german, override: true)
var english: [String: String] = [:]
entries(try readCSV("copy.en.csv"), into: &english)
func placeholders(_ text: String) -> Set<String> {
    let regex = try! NSRegularExpression(pattern: #"\{([^{}]+)\}"#)
    let range = NSRange(text.startIndex..., in: text)
    return Set(regex.matches(in: text, range: range).compactMap { match in
        Range(match.range(at: 1), in: text).map { String(text[$0]) }
    })
}
func reject(_ message: String) -> Never {
    FileHandle.standardError.write(Data(("Copy generation error: " + message + "\n").utf8))
    exit(1)
}
let missing = Set(german.keys).subtracting(english.keys).sorted()
let extra = Set(english.keys).subtracting(german.keys).sorted()
if !missing.isEmpty || !extra.isEmpty { reject("language keys differ; missing: \(missing), extra: \(extra)") }
for key in german.keys.sorted() where placeholders(german[key]!) != placeholders(english[key]!) {
    reject("placeholder names differ for key \(key)")
}
func generate(_ name: String, rb: Bool, destination: String) throws {
    let keys = german.keys.filter { $0.hasPrefix("rb.") == rb }.sorted()
    var lines = ["// Generated by tools/gen.swift from resources/. Do not edit.", "import RBContract", "", "enum \(name) {"]
    for (language, table) in [("de", german), ("en", english)] {
        lines.append("    static let \(language): [String: String] = [")
        for key in keys { lines.append("        \(swiftLiteral(key)): \(swiftLiteral(table[key]!)),") }
        lines.append("    ]")
    }
    lines += ["    static let active = AppLanguage.current == .en ? en : de", "}", ""]
    try lines.joined(separator: "\n").write(to: root.appendingPathComponent(destination), atomically: true, encoding: .utf8)
}
try generate("CopyTable", rb: false, destination: "Sources/RBUI/Core/Copy.generated.swift")
try generate("RBCopy", rb: true, destination: "Sources/rb/RBCopy.generated.swift")
let count = german.count
if copyOnly {
    print("copy keys: \(count)")
    exit(0)
}

// tokens.json → tokens.css (same rule as prototype/build-data.mjs)
let tokens = try JSONSerialization.jsonObject(with: Data(contentsOf: resources.appendingPathComponent("tokens.json")))
    as! [String: Any]
var css: [String] = []
for group in tokens.keys.sorted() where !group.hasPrefix("$") {
    guard let values = tokens[group] as? [String: Any] else { continue }
    for key in values.keys.sorted() {
        if let v = (values[key] as? [String: Any])?["value"] { css.append("  --\(group)-\(key): \(v);") }
    }
}
let ui = root.appendingPathComponent("ui")
try FileManager.default.createDirectory(at: ui, withIntermediateDirectories: true)
try ("/* generated from resources/tokens.json by tools/gen.swift; do not edit */\n:root {\n"
     + css.joined(separator: "\n") + "\n}\n").write(to: ui.appendingPathComponent("tokens.css"), atomically: true, encoding: .utf8)

